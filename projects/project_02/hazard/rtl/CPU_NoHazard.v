`timescale 1ns / 1ps

module CPU_NoHazard (PC_NEXT,READ_DATA_1,READ_DATA_2,READ_DATA_1_ID_EX, READ_DATA_2_ID_EX, 
    ALU_Input0, ALU_Input1,ALU_RESULT_EX_MEM,ALU_result_MEM_WB, WRITE_DATA,FORWARDA, FORWARDB,WRITE_ADDR, 
    WRITE_ADDR_EX_MEM,Write_Addr_Mem_WB, CLK, RST) ;
	output [31:0]PC_NEXT,READ_DATA_1,READ_DATA_2,READ_DATA_1_ID_EX, READ_DATA_2_ID_EX, ALU_Input0, ALU_Input1,ALU_RESULT_EX_MEM,ALU_result_MEM_WB, WRITE_DATA;
	output [1:0] FORWARDA, FORWARDB;
	output [4:0]WRITE_ADDR, WRITE_ADDR_EX_MEM,Write_Addr_Mem_WB ;
	input CLK, RST ;
	wire [31:0] PC_IN, INSTRUCTION,  Signextend_Out, ALU_result, DataMem_out,
		PC_4, SFL32_Output, PC_Branch, branch_result ;  
	wire [27:0]SFL28_Output ;
	wire [3:0]ALU_Ctrl ; 
	wire [1:0]ALUOP ; 
	wire REGDST, ALUSRC, MEMTOREG, REGWRITE, MEMREAD, MEMWRITE, BRANCH, ZERO, branch_select ;  



	wire [31:0]INSTRUCTION_IF_ID, PC_4_IFID_out ;

	wire REGWRITE_ID_EX, MEMTOREG_ID_EX, BRANCH_ID_EX, MEMREAD_ID_EX, MEMWRITE_ID_EX, ALUSRC_ID_EX, REGDST_ID_EX ; 
	wire [1:0]ALUOP_ID_EX ;
	wire [31:0]PC_4_IDEX_out, SE_ID_EX;
	wire [4:0]RD_ID_EX, RT_ID_EX ;


	wire REGWRITE_EX_MEM, MEMTOREG_EX_MEM, BRANCH_EX_MEM, MEMREAD_EX_MEM, MEMWRITE_EX_MEM, ZERO_EX_MEM ;
	wire [31:0] ADD_RESULT_EX_MEM, READ_DATA_2_EX_MEM ;
	

	wire REGWRITE_MEM_WB, MemToReg_MEM_WB ;
	wire [31:0]DataMemory_Output_MEM_WB    ;



	wire PCWrite ;
	PC Program_Counter(.PC_OUT(PC_NEXT), .PC_IN(PC_IN), .PCWrite(PCWrite), .CLK(CLK), .RST(RST));
	InstructionMemory IM(.INSTRUCTION(INSTRUCTION), .ADDR(PC_NEXT), .RST(RST)) ;

	wire [31:0]constant  ;
	assign constant = 32'd4 ;

	Add Add_1(.OUT(PC_4), .IN0(PC_NEXT), .IN1(constant) ) ;

	wire IF_ID_WRTIE ;
	IF_ID IF_ID_Reg(.PC_4_out(PC_4_IFID_out), .IM_out(INSTRUCTION_IF_ID), .PC_4(PC_4), .IM(INSTRUCTION), .IF_ID_WRTIE(IF_ID_WRTIE), .CLK(CLK), .RST(RST));

	wire CTRL_SEL ; 
	Controller CTLER( .REGDST(REGDST), .ALUSRC(ALUSRC), .MEMTOREG(MEMTOREG), .REGWRITE(REGWRITE), 
					.MEMREAD(MEMREAD), .MEMWRITE(MEMWRITE), .BRANCH(BRANCH), .ALUOP(ALUOP), .OPCODE(INSTRUCTION_IF_ID[31:26]), .Sel(CTRL_SEL) ) ;  

	Register_file RF(.READ_DATA_1(READ_DATA_1), .READ_DATA_2(READ_DATA_2), .READ_ADDR_1(INSTRUCTION_IF_ID[25:21]), .READ_ADDR_2(INSTRUCTION_IF_ID[20:16]), 
	.WRITE_ADDR(Write_Addr_Mem_WB), .WRITE_DATA(WRITE_DATA), .REGWRITE(REGWRITE_MEM_WB), .CLK(CLK),.RST(RST) );   

	Sign_Extend  SE(.OUT_32BITS(Signextend_Out) , .IN_16BITS(INSTRUCTION_IF_ID[15:0] ) ) ;

	
	wire [4:0]RS_ID_EX ;
	ID_EX ID_EX_Reg(.REGWRITE_out(REGWRITE_ID_EX), .MEMTOREG_out(MEMTOREG_ID_EX), .BRANCH_out(BRANCH_ID_EX), .MEMREAD_out(MEMREAD_ID_EX),
	 .MEMWRITE_out(MEMWRITE_ID_EX), .ALUSRC_out(ALUSRC_ID_EX), .REGDST_out(REGDST_ID_EX), .ALUOP_out(ALUOP_ID_EX), 
	 .PC_4_out(PC_4_IDEX_out), .ReadData_1_out(READ_DATA_1_ID_EX), .ReadData_2_out(READ_DATA_2_ID_EX), .Signextend_Reg(SE_ID_EX), .RD_out(RD_ID_EX), .RT_out(RT_ID_EX), .RS_out(RS_ID_EX),
	.REGWRITE(REGWRITE), .MEMTOREG(MEMTOREG), .BRANCH(BRANCH), .MEMREAD(MEMREAD), .MEMWRITE(MEMWRITE), .REGDST(REGDST), .ALUSRC(ALUSRC), .ALUOP(ALUOP), 
	.PC_4(PC_4_IFID_out), .READ_DATA_1(READ_DATA_1), .READ_DATA_2(READ_DATA_2), .SE_REG(Signextend_Out), 
	.RD(INSTRUCTION_IF_ID[15:11]), .RT(INSTRUCTION_IF_ID[20:16]), .RS(INSTRUCTION_IF_ID[25:21]), .CLK(CLK), .RST(RST) );


	Mux_5Bits Mux5_1(.OUT(WRITE_ADDR), .IN0(RT_ID_EX), .IN1(RD_ID_EX), .SEL(REGDST_ID_EX)) ; 
	ALU_Controller ALUCTLER( .ALU_CONTROL(ALU_Ctrl), .ALU_OP(ALUOP_ID_EX), .FUNCTION_FIELD(SE_ID_EX[5:0]) ) ; 
	Shift_Left_2_32BitsTo32Bits SFL32_1( .Out(SFL32_Output), .In(SE_ID_EX) ) ;
	Add Add_2(.OUT(PC_Branch), .IN0(PC_4_IDEX_out), .IN1(SFL32_Output) ) ;

	
	Mux_32Bits_3input Mux_32Bits_3input_1(.OUT(ALU_Input0), .IN0(READ_DATA_1_ID_EX), .IN1(WRITE_DATA), .IN2(ALU_RESULT_EX_MEM), .SEL(FORWARDA) ) ;   
 	
	wire [31:0]Mux32_1_IN0 ;
 	Mux_32Bits_3input Mux_32Bits_3input_2(.OUT(Mux32_1_IN0), .IN0(READ_DATA_2_ID_EX), .IN1(WRITE_DATA), .IN2(ALU_RESULT_EX_MEM), .SEL(FORWARDB) ) ;   

	
	Mux_32Bits Mux32_1(.OUT(ALU_Input1), .IN0(Mux32_1_IN0), .IN1(SE_ID_EX), .SEL(ALUSRC_ID_EX) ) ;
		
	ALU ALU_1(.OUT(ALU_result), .ZERO(ZERO), .IN0(ALU_Input0), .IN1(ALU_Input1), .ALU_CONTROL(ALU_Ctrl) ) ; 


	ForwardingUnit FWUnit(.FORWARDA(FORWARDA), .FORWARDB(FORWARDB), .RS_in(RS_ID_EX) , .RT_in(RT_ID_EX), .RD_EX_MEM(WRITE_ADDR_EX_MEM), .RD_MEM_WB(Write_Addr_Mem_WB), .REGWRITE_EX_MEM(REGWRITE_EX_MEM), .REGWRITE_MEM_WB(REGWRITE_MEM_WB) );   
	
	EX_MEM EX_MEM_Reg(.REGWRITE_out(REGWRITE_EX_MEM), .MEMTOREG_out(MEMTOREG_EX_MEM), .BRANCH_out(BRANCH_EX_MEM), .MEMREAD_out(MEMREAD_EX_MEM), .MEMWRITE_out(MEMWRITE_EX_MEM),
	.ADD_RESULT_out(ADD_RESULT_EX_MEM), .ALU_RESULT_out(ALU_RESULT_EX_MEM), .READ_DATA_2_out(READ_DATA_2_EX_MEM), .WRITE_ADDR_out(WRITE_ADDR_EX_MEM), .ZERO_out(ZERO_EX_MEM),
	.CLK(CLK), .RST(RST), .REGWRITE(REGWRITE_ID_EX), .MEMTOREG(MEMTOREG_ID_EX), .BRANCH(BRANCH_ID_EX), .MEMREAD(MEMREAD_ID_EX), .MEMWRITE(MEMWRITE_ID_EX),
	.ADD_RESULT(PC_Branch), .ALU_RESULT(ALU_result), .READ_DATA_2(READ_DATA_2_ID_EX), .WRITE_ADDR(WRITE_ADDR), .ZERO(ZERO));


	and and1(branch_select, BRANCH_EX_MEM, ZERO_EX_MEM) ;

	DataMemory DM( .READ_DATA(DataMem_out), .ADDR(ALU_RESULT_EX_MEM), .WRITE_DATA(READ_DATA_2_EX_MEM), 
					.MEM_WRITE(MEMWRITE_EX_MEM), .MEM_READ(MEMREAD_EX_MEM), .RST(RST), .CLK(CLK) );

	MEM_WB MEM_WB_Reg(.WRITE_ADDR_out(Write_Addr_Mem_WB), .ALU_result_out(ALU_result_MEM_WB), .READ_DATA_out(DataMemory_Output_MEM_WB), .WB_RegWrite_out(REGWRITE_MEM_WB), .WB_MemToReg_out(MemToReg_MEM_WB), 
	.WRITE_ADDR(WRITE_ADDR_EX_MEM), .ALU_result(ALU_RESULT_EX_MEM), .READ_DATA(DataMem_out), .WB_RegWrite(REGWRITE_EX_MEM), .WB_MemToReg(MEMTOREG_EX_MEM), .CLK(CLK), .RST(RST));


	Mux_32Bits Mux32_2(.OUT(WRITE_DATA), .IN0(DataMemory_Output_MEM_WB), .IN1(ALU_result_MEM_WB), .SEL(MemToReg_MEM_WB) ) ; 

	Mux_32Bits Mux32_3(.OUT(PC_IN), .IN0(PC_4), .IN1(ADD_RESULT_EX_MEM), .SEL(branch_select) ) ;

	Hazard_detection_unit HDUnit(.PCWRITE(PCWrite), .IF_ID_WRITE(IF_ID_WRTIE), .CTRL_SEL(CTRL_SEL), 
		.RS_IF_ID(INSTRUCTION_IF_ID[25:21]), .RT_IF_ID(INSTRUCTION_IF_ID[20:16]), .RT_ID_EX(RT_ID_EX), .MEMREAD_ID_EX(MEMREAD_ID_EX) );

endmodule 
